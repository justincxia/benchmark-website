-- The hidden SONA survey (/arena/sonasurvey). Isolated from the arena and the leaderboard:
-- nothing else reads or writes these tables. RLS on, no policies, no anon/authenticated grants.

create table public.sona_sessions (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  consented_at timestamptz not null default now(),
  completed_at timestamptz,
  -- The ?id= SONA passes in the study URL, if any.
  sona_id text,
  seed bigint not null,
  -- The 50 clip basenames, in play order.
  block jsonb not null check (jsonb_typeof(block) = 'array'),
  user_agent text,
  -- ?debug=1 sessions (non-production only; a 3-clip block).
  debug boolean not null default false
);

-- Mirrors public.responses, keyed by (session_id, trial_index) instead of
-- (participant, session, round), plus response_ms.
create table public.sona_responses (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.sona_sessions (id) on delete cascade,
  trial_index integer not null check (trial_index between 0 and 49),
  experiment integer not null check (experiment in (1, 2)),
  model text not null,
  clip text not null,
  condition text not null,
  variant text,
  take integer not null,
  naturalness integer not null check (naturalness between 1 and 5),
  human_or_ai text check (human_or_ai in ('Human', 'AI')),
  question_answered text,
  intended_question text,
  interpretation text check (interpretation in ('A', 'B')),
  intended_interpretation text check (intended_interpretation in ('A', 'B')),
  listened_ms integer not null,
  -- Time from the clip first being shown to Submit.
  response_ms integer not null check (response_ms >= 0),
  created_at timestamptz not null default now(),
  constraint sona_responses_trial_unique unique (session_id, trial_index)
);

-- Kept apart from the answers; joined only through session_id.
create table public.sona_contacts (
  id bigint generated by default as identity primary key,
  session_id uuid not null unique references public.sona_sessions (id) on delete cascade,
  name text not null check (length(name) between 1 and 200),
  email text not null check (length(email) between 3 and 320),
  created_at timestamptz not null default now()
);

alter table public.sona_sessions enable row level security;
alter table public.sona_responses enable row level security;
alter table public.sona_contacts enable row level security;

revoke all on public.sona_sessions, public.sona_responses, public.sona_contacts from anon, authenticated;
